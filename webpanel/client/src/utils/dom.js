// ----- DOM builder -----
export function el(tag, attrs = {}, ...children) {
  const node = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs)) {
    if (v === null || v === undefined) continue;
    if (k === "on") continue;
    if (k.startsWith("on")) { node.addEventListener(k.slice(2).toLowerCase(), v); }
    else if (k === "class" && typeof v === "string") { node.className = v; }
    else if (k === "dataset" && typeof v === "object") { Object.assign(node.dataset, v); }
    else if (k === "html") { node.innerHTML = v; }
    else { node.setAttribute(k, v); }
  }
  for (const child of children) {
    if (typeof child === "string" || typeof child === "number") { node.appendChild(document.createTextNode(String(child))); }
    else if (child.nodeType) { node.appendChild(child); }
    else if (Array.isArray(child)) { child.forEach(c => node.appendChild(c)); }
  }
  return node;
}

export function h1(t) { return el("h1", null, t); }
export function h2(t) { return el("h2", null, t); }
export function h3(t) { return el("h3", null, t); }
export function p(t, cls) { return typeof cls === "string" ? el("p", { class: cls }, t) : el("p", {}, t); }

export function getTheme() { return localStorage.getItem("webpanel_theme") || "light"; }

export function setTheme(t) { localStorage.setItem("webpanel_theme", t); document.documentElement.setAttribute("data-theme", t); }
export function btn(label, cls, onclick) {
  return el("button", { class: cls, onclick }, label);
}
export function badge(label, cls) { return el("span", { class: `badge ${cls}` }, label); }

// Empty-state box
export function emptyState(title, description, icon = icon.dashboard) {
  return el("div", { class: "empty-state" },
    el("svg", { width: 48, height: 48 }, icon),
    el("h3", null, title),
    p(description, "mt-1")
  );
}

// Loading ring
export function loading() {
  return el("span", { class: "loading-ring" }, el("span", { class: "spinner" }));
}

// Copy to clipboard helper
export function copyText(text) {
  return navigator.clipboard && navigator.clipboard.writeText
    ? navigator.clipboard.writeText(text)
    : new Promise((res, rej) => {
        const ta = document.createElement("textarea");
        ta.value = text;
        ta.style.position = "fixed";
        ta.style.opacity = "0";
        document.body.appendChild(ta);
        ta.select();
        try { document.execCommand("copy"); res(); } catch { rej(); }
        document.body.removeChild(ta);
      });
}
